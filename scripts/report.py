#!/usr/bin/env python3
"""
Stage 8: aggregate everything into the paper's Section 5 tables and Figures 2-4.

Reads results/*_raw.csv (from run_policy.py and ablate.py), results/e1_gap.md, results/calibration.csv,
results/reliability_bins.csv and results/confusion_*.csv. Writes:
  results/paper_tables.md           Tables 5.1-5.4 (+ calibration and workload), mean ± SD over seeds
  results/stats_tests.csv           paired t-test and Wilcoxon across seeds (proposed vs baselines)
  results/fig2_confusion.png, fig3_risk_coverage.png, fig4_reliability.png, fig1b_gap.png

Usage:  python scripts/report.py --results results --backbone efficientnet_b0
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np
import pandas as pd

from tomato_agent.classes import CLASSES, DISPLAY_EN
from tomato_agent.io_utils import write_csv

PCT = {"acc_all", "acc@90", "acc@80", "acc@70", "ece", "coverage", "selective_accuracy", "deferral_rate",
       "retake_rate", "system_accuracy_oracle", "static_acc", "quality_retake_acc", "flag_rate_first_photo",
       "auto_error_rate", "final_accuracy_all", "retake_rescued", "ece_before", "ece_after"}
METHOD_LABEL = {"B1_static": "B1 Static", "B2_ensemble": "B2 Ensemble", "B3_threshold_only": "B3 Threshold only",
                "proposed/pess": "Proposed (pessimistic retake)", "proposed/opt": "Proposed (optimistic retake)"}


def fmt(series, col):
    v = series.dropna().astype(float)
    if v.empty:
        return "n/a"
    k = 100 if col in PCT else 1
    m, s = v.mean() * k, (v.std(ddof=1) * k if len(v) > 1 else 0.0)
    return f"{m:.1f} ± {s:.1f}" if k == 100 else f"{m:.4f} ± {s:.4f}"


def md_table(df, keys, cols, names=None):
    names = names or cols
    head = "| " + " | ".join(keys + names) + " |\n|" + "---|" * (len(keys) + len(cols)) + "\n"
    lines = []
    for kv, g in df.groupby(keys, sort=False):
        kv = kv if isinstance(kv, tuple) else (kv,)
        lines.append("| " + " | ".join(map(str, kv)) + " | " + " | ".join(fmt(g[c], c) if c in g else "n/a" for c in cols) + " |")
    return head + "\n".join(lines) + "\n"


def method_key(r):
    return f"{r['method']}/{r['mode']}" if r["method"] == "proposed" else r["method"]


def paired(a, b):
    from scipy.stats import ttest_rel, wilcoxon
    a, b = np.asarray(a, float), np.asarray(b, float)
    out = {"n": len(a), "mean_diff": float((a - b).mean())}
    if len(a) >= 2 and np.any(a != b):
        out["t_p"] = float(ttest_rel(a, b).pvalue)
        try:
            out["wilcoxon_p"] = float(wilcoxon(a, b).pvalue)
        except ValueError:
            out["wilcoxon_p"] = float("nan")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", default="results")
    ap.add_argument("--backbone", default=None, help="main backbone for Tables 5.2-5.4 (default: first)")
    ap.add_argument("--cost", default="10:1")
    ap.add_argument("--temperature", default="pv")
    ap.add_argument("--set", default="pd_test")
    args = ap.parse_args()
    R = Path(args.results)
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    md = ["# Results (auto-generated by scripts/report.py)\n",
          "All numbers are mean ± SD over seeds. Percentages unless noted. Expert = oracle (ground truth).\n"]
    e3 = pd.read_csv(R / "e3_reliability_raw.csv")
    bb = args.backbone or sorted(e3.loc[e3.method == "proposed", "backbone"].unique())[0]
    md.append(f"Main backbone: **{bb}**, cost ratio C_err:C_def = **{args.cost}**, temperature fitted on "
              f"**{'PlantVillage val' if args.temperature == 'pv' else 'PlantDoc calibration split'}**, test set **{args.set}**.\n")

    # ---- 5.1
    if (R / "e1_gap.md").exists():
        md += ["\n## Table 5.1 Laboratory-to-field gap (RQ1)\n", (R / "e1_gap.md").read_text(encoding="utf-8")]
        g = pd.read_csv(R / "e1_gap_per_run.csv")
        fig, ax = plt.subplots(figsize=(6, 3.2))
        agg = g.groupby("backbone")[["pv_test_acc", "pd_test_acc"]].agg(["mean", "std"])
        x = np.arange(len(agg))
        for i, (col, lab) in enumerate((("pv_test_acc", "PlantVillage test"), ("pd_test_acc", "PlantDoc (field)"))):
            ax.bar(x + (i - 0.5) * 0.38, agg[(col, "mean")] * 100, 0.38, yerr=agg[(col, "std")].fillna(0) * 100, label=lab, capsize=3)
        ax.set_xticks(x, agg.index, fontsize=8)
        ax.set_ylabel("accuracy (%)")
        ax.legend(fontsize=8)
        ax.set_title("Lab-to-field gap")
        fig.tight_layout()
        fig.savefig(R / "fig1b_gap.png", dpi=200)
        plt.close(fig)

    # ---- calibration
    if (R / "calibration.csv").exists():
        c = pd.read_csv(R / "calibration.csv")
        md += ["\n## Calibration (Section 5.3, Figure 4)\n",
               md_table(c, ["backbone", "test_set", "temperature"], ["T", "ece_before", "ece_after", "nll_before", "nll_after"],
                        ["T", "ECE before", "ECE after", "NLL before", "NLL after"])]

    # ---- 5.2
    if (R / "e2_quality_retake_raw.csv").exists():
        e2 = pd.read_csv(R / "e2_quality_retake_raw.csv")
        e2 = e2[(e2.backbone == bb) & (e2.set == args.set)]
        piv = []
        for deg, g in e2.groupby("degradation", sort=False):
            o, p = g[g["mode"] == "opt"], g[g["mode"] == "pess"]
            piv.append(f"| {deg} | {fmt(p.static_acc, 'static_acc')} | {fmt(o.quality_retake_acc, 'quality_retake_acc')} | "
                       f"{fmt(p.quality_retake_acc, 'quality_retake_acc')} | {fmt(p.retake_rate, 'retake_rate')} |")
        md += ["\n## Table 5.2 Quality agent and retakes (RQ2)\n",
               "No deferral here: the system always answers after at most one retake.\n\n",
               "| Degradation | Static classifier accuracy | With quality check + retake (optimistic) | (pessimistic) | Retake rate |\n|---|---|---|---|---|\n",
               "\n".join(piv) + "\n"]

    # ---- 5.3
    sub = e3[(e3.set == args.set)]
    sub = sub[((sub.method == "B1_static")) |
              ((sub.method == "B2_ensemble") & (sub.temperature == args.temperature)) |
              ((sub.method.isin(["B3_threshold_only", "proposed"])) & (sub.temperature == args.temperature) &
               (sub.cost == args.cost) & (sub.backbone == bb))]
    sub = sub[(sub.method != "B1_static") | (sub.backbone == bb)].copy()
    sub["Method"] = [METHOD_LABEL[method_key(r)] for _, r in sub.iterrows()]
    order = list(METHOD_LABEL.values())
    sub["_o"] = sub["Method"].map(order.index)
    sub = sub.sort_values(["scenario", "_o"])
    md += ["\n## Table 5.3 Reliability through gated deferral (RQ3)\n",
           "Accuracy at x% coverage = accuracy on the x% of cases the method trusts most (B1 has no abstention; its "
           "row ranks by raw softmax confidence for reference). AURC is unitless, lower is better.\n\n",
           md_table(sub, ["scenario", "Method"], ["acc_all", "acc@90", "acc@80", "acc@70", "ece", "aurc"],
                    ["Field accuracy (all cases)", "Acc @90%", "Acc @80%", "Acc @70%", "ECE", "AURC"]),
           "\n**Operating point chosen by the cost rule** (proposed and B3):\n\n",
           md_table(sub[sub.method.isin(["B3_threshold_only", "proposed"])], ["scenario", "Method"],
                    ["coverage", "selective_accuracy", "deferral_rate", "retake_rate", "system_accuracy_oracle", "expected_cost"],
                    ["Coverage", "Accuracy on accepted", "Deferral rate", "Retake rate", "System accuracy (oracle expert)", "Cost"])]

    # paired tests
    tests = []
    for scen in sub.scenario.unique():
        s = sub[sub.scenario == scen]
        prop = s[(s.method == "proposed") & (s["mode"] == "pess")].set_index("seed")
        for other in ("B3_threshold_only", "B2_ensemble"):
            o = s[s.method == other].set_index("seed")
            common = sorted(set(prop.index) & set(o.index))
            for metric in ("acc@80", "acc@90", "aurc"):
                if common:
                    tests.append({"scenario": scen, "comparison": f"proposed(pess) vs {other}", "metric": metric,
                                  **paired(prop.loc[common, metric], o.loc[common, metric])})
    write_csv(R / "stats_tests.csv", tests)
    if tests:
        md += ["\n**Paired tests across seeds** (positive mean_diff = proposed higher; for AURC lower is better):\n\n",
               "| Scenario | Comparison | Metric | n | Mean diff | t-test p | Wilcoxon p |\n|---|---|---|---|---|---|---|\n"]
        md += [f"| {t['scenario']} | {t['comparison']} | {t['metric']} | {t['n']} | {t['mean_diff']:.4f} | "
               f"{t.get('t_p', float('nan')):.4f} | {t.get('wilcoxon_p', float('nan')):.4f} |\n" for t in tests]
        md.append("\nWith 5 seeds the smallest possible two-sided Wilcoxon p is 0.0625; report the t-test and the effect size.\n")

    # ---- 5.4 + E5
    if (R / "e4_ablation_raw.csv").exists():
        e4 = pd.read_csv(R / "e4_ablation_raw.csv")
        e4 = e4[(e4.backbone == bb)]
        md += ["\n## Table 5.4 Ablation and workload (RQ4)\n",
               md_table(e4[e4["mode"] == "pess"], ["variant"],
                        ["acc@80", "coverage", "selective_accuracy", "deferral_rate", "retake_rate", "system_accuracy_oracle"],
                        ["Field acc @80% coverage", "Coverage", "Accuracy on accepted", "Deferral rate", "Retake rate", "System accuracy"])]
    if (R / "e5_cost_workload_raw.csv").exists():
        e5 = pd.read_csv(R / "e5_cost_workload_raw.csv")
        e5 = e5[(e5.backbone == bb) & (e5["mode"] == "pess")]
        md += ["\n**Cost ratio and expert workload** (per 1,000 farmer cases, pessimistic retakes):\n\n",
               md_table(e5, ["cost"], ["tau_accept", "tau_defer", "expert_cases_per_1000", "retakes_per_1000",
                                       "wrong_auto_answers_per_1000", "system_accuracy_oracle"],
                        ["tau_accept", "tau_defer", "Expert cases", "Retakes", "Wrong automatic answers", "System accuracy"])]

    (R / "paper_tables.md").write_text("".join(md), encoding="utf-8")

    # ---- figures
    cm_path = R / f"confusion_{bb}_{args.set}.csv"
    if cm_path.exists():
        cm = pd.read_csv(cm_path).set_index("true")[CLASSES].values.astype(float)
        cmn = cm / np.maximum(cm.sum(1, keepdims=True), 1)
        fig, ax = plt.subplots(figsize=(6.2, 5.4))
        im = ax.imshow(cmn, cmap="Greens", vmin=0, vmax=1)
        names = [DISPLAY_EN[c] for c in CLASSES]
        ax.set_xticks(range(8), names, rotation=45, ha="right", fontsize=7)
        ax.set_yticks(range(8), names, fontsize=7)
        for i in range(8):
            for j in range(8):
                ax.text(j, i, f"{cmn[i, j]:.2f}", ha="center", va="center", fontsize=6, color="white" if cmn[i, j] > .5 else "black")
        ax.set_xlabel("predicted")
        ax.set_ylabel("true")
        ax.set_title(f"Field confusion matrix ({bb}, all seeds)")
        fig.colorbar(im, fraction=0.046)
        fig.tight_layout()
        fig.savefig(R / "fig2_confusion.png", dpi=200)
        plt.close(fig)

    if (R / "curves_raw.csv").exists():
        cv = pd.read_csv(R / "curves_raw.csv")
        cv = cv[(cv.set == args.set)]
        scen = sorted(cv.scenario.unique())
        fig, axes = plt.subplots(1, len(scen), figsize=(5.2 * len(scen), 3.8), squeeze=False)
        for ax, sc in zip(axes[0], scen):
            for key, lab in METHOD_LABEL.items():
                meth, _, mode = key.partition("/")
                g = cv[(cv.scenario == sc) & (cv.method == meth)]
                if mode:
                    g = g[g["mode"] == mode]
                if meth == "B1_static":
                    g = g[g.backbone == bb]
                elif meth != "B2_ensemble":
                    g = g[(g.backbone == bb) & (g.temperature == args.temperature) & (g.cost == args.cost)]
                else:
                    g = g[g.temperature == args.temperature]
                if g.empty:
                    continue
                a = g.groupby("coverage").risk.agg(["mean", "std"]).fillna(0)
                ax.plot(a.index, a["mean"] * 100, label=lab, lw=1.6)
                ax.fill_between(a.index, (a["mean"] - a["std"]) * 100, (a["mean"] + a["std"]) * 100, alpha=0.15)
            ax.set_xlabel("coverage (share of cases answered automatically)")
            ax.set_ylabel("risk (% errors among answered)")
            ax.set_title(f"{args.set}, {sc} conditions")
            ax.grid(alpha=0.3)
        axes[0][0].legend(fontsize=7)
        fig.tight_layout()
        fig.savefig(R / "fig3_risk_coverage.png", dpi=200)
        plt.close(fig)

    if (R / "reliability_bins.csv").exists():
        rb = pd.read_csv(R / "reliability_bins.csv")
        rb = rb[(rb.backbone == bb) & (rb.test_set == args.set)]
        fig, ax = plt.subplots(figsize=(4.4, 4.2))
        ax.plot([0, 1], [0, 1], "k--", lw=0.8)
        for tag, lab in (("before", "before"), ("after_Tpv", "after T (PlantVillage)"), ("after_Tpd", "after T (field)")):
            g = rb[rb.calibration == tag].dropna(subset=["conf"])
            if g.empty:
                continue
            w = g.groupby("bin_lo").apply(lambda d: pd.Series({
                "conf": np.average(d.conf, weights=d["count"]), "acc": np.average(d.acc, weights=d["count"])}), include_groups=False)
            ax.plot(w.conf, w.acc, "o-", ms=3, label=lab)
        ax.set_xlabel("confidence")
        ax.set_ylabel("accuracy")
        ax.set_title(f"Reliability ({bb}, {args.set})")
        ax.legend(fontsize=7)
        fig.tight_layout()
        fig.savefig(R / "fig4_reliability.png", dpi=200)
        plt.close(fig)

    print(f"Wrote {R}/paper_tables.md, stats_tests.csv and figures")


if __name__ == "__main__":
    main()
